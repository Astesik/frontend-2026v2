import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import vm from 'node:vm'
import ts from 'typescript'
import { parse } from '@vue/compiler-sfc'
import { computed, nextTick, ref, watch } from 'vue'

const transpile = source => ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText
const utilities = readFileSync(new URL('../src/utils/localPositionHistory.ts', import.meta.url), 'utf8')
const utilityAst = ts.createSourceFile('utils.ts', utilities, ts.ScriptTarget.Latest, true)
const formatters = utilityAst.statements.filter(node => ts.isFunctionDeclaration(node) && ['historyPointSpeed', 'historyPointFuel'].includes(node.name?.text))
const formatting = {}
vm.runInNewContext(transpile(formatters.map(node => node.getText(utilityAst).replace('export ', '')).join('\n')) + '\nthis.formatters = { historyPointSpeed, historyPointFuel }', formatting)
const { historyPointSpeed, historyPointFuel } = formatting.formatters
assert.equal(historyPointSpeed(82.74), '83 km/h')
assert.equal(historyPointSpeed(0), '0 km/h')
assert.equal(historyPointSpeed(null), '—')
assert.equal(historyPointFuel({ fuelLiters: 120, fuelPct: 40 }), '120 l (40%)')
assert.equal(historyPointFuel({ fuelLiters: null, fuelPct: 0 }), '0%')
assert.equal(historyPointFuel({ fuelLiters: 0, fuelPct: 0 }), '0 l (0%)')
assert.equal(historyPointFuel({ fuelLiters: 120.25, fuelPct: null }), '120,25 l')
assert.equal(historyPointFuel({ fuelLiters: NaN, fuelPct: 40 }), '40%')
assert.equal(historyPointFuel({ fuelLiters: null, fuelPct: null }), '')

const source = parse(readFileSync(new URL('../src/views/MapView.vue', import.meta.url), 'utf8')).descriptor.scriptSetup.content
const ast = ts.createSourceFile('MapView.ts', source, ts.ScriptTarget.Latest, true)
const functionSource = name => ast.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === name).getText(ast)
const watchers = ast.statements.filter(node => ts.isExpressionStatement(node) && ts.isCallExpression(node.expression) && node.expression.expression.getText(ast) === 'watch' && ['filteredVehicles', 'selectedVehicleId'].includes(node.expression.arguments[0]?.getText(ast)))
const selectedVehicleId = ref('99'), filteredVehicles = ref([]), activeMode = ref('history')
const route = [{ id: 1 }, { id: 2 }]
let clears = 0, historyRequests = 0, refreshes = 0
const stops = []
const state = {
  activeMode, selectedVehicleId, filteredVehicles, workspaceActive: ref(true),
  selectedVehicle: computed(() => selectedVehicleId.value ? { id: selectedVehicleId.value } : null),
  fleetStore: {
    currentPositionHistoryVehicleId: '99', currentPositionHistoryMode: 'custom',
    fetchLastPositions: async () => { refreshes++; filteredVehicles.value = [{ id: '1' }] },
  },
  positionHistory: { records: ref(route) }, vehicleDetailsDrawerOpen: ref(false), vehicleDrawerTab: ref('info'),
  googleMap: ref(null), mapSettings: { map: { followVehicle: false } }, renderMarkers() {}, focusVehicle() {},
  clearTodayRoute() { clears++ }, clearPositionHistoryData() { clears++ },
  renderTodayRoute: async () => { historyRequests++ },
  watch: (...args) => stops.push(watch(...args)),
}
vm.runInNewContext(transpile(watchers.map(node => node.getText(ast)).join('\n') + '\n' + functionSource('refreshLastPositions')) + '\nthis.refresh = refreshLastPositions', state)
for (let i = 0; i < 3; i++) {
  await state.refresh()
  await nextTick()
  assert.equal(selectedVehicleId.value, '99', 'Live list filters must not deselect the vehicle in custom history')
  assert.equal(state.positionHistory.records.value.length, 2)
  assert.equal(clears, 0, 'Refresh must preserve the generated route')
  assert.equal(historyRequests, 0, 'Custom history must not be regenerated by position polling')
}
assert.equal(refreshes, 3)
vm.runInNewContext(transpile(functionSource('renderTodayRoute')) + '\nthis.renderToday = renderTodayRoute', state)
await state.renderToday()
assert.equal(clears, 0, 'Today-route callbacks must not clear custom history')
activeMode.value = 'list'
filteredVehicles.value = [{ id: '1' }]
await nextTick()
assert.equal(selectedVehicleId.value, null, 'Keep selection cleanup in the regular vehicle list')
stops.forEach(stop => stop())
let appended = 0
const live = {
  workspaceActive: ref(true), activeMode: ref('list'), selectedVehicle: ref({ id: '99' }), selectedVehicleId: ref('99'),
  fleetStore: {
    currentPositionHistoryMode: 'today', currentPositionHistoryVehicleId: '99',
    currentPositionHistoryRange: { from: '2026-10-26T23:00:00Z' }, isRouteHistoryLoading: false,
    appendTodayRouteHistory: async () => { appended++ },
    fetchTodayRouteHistory() { assert.fail('Equivalent timestamps must append rather than reload') },
  },
  todayHistoryRange: () => ({ from: '2026-10-26T23:00:00.000Z' }),
  googleMap: ref({}), window: { google: { maps: {} } }, mapSettings: { map: { todayRoute: true } }, canReadLocalHistory: ref(true),
  todayRouteRequestId: 1, positionHistory: { lastTimestamp: () => '2026-10-27T10:00:00Z' }, syncTodayRouteRender() {},
  clearTodayRoute() { assert.fail('Polling must not clear the route') }, clearPositionHistoryData() { assert.fail('Polling must not clear stored history') }, showRouteHistoryErrorToast(error) { throw error },
}
vm.runInNewContext(transpile(functionSource('renderTodayRoute')) + '\nthis.refresh = renderTodayRoute', live)
await live.refresh({ append: true })
assert.equal(appended, 1, 'Different ISO representations of the same range start must use incremental refresh')
console.log('PASS: integer speed, compact fuel values, zero/missing data, repeated position refresh preserving custom history and selection cleanup in list mode.')
